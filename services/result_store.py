"""Durable immutable result snapshots and their small mutable projections."""

from __future__ import annotations

import hashlib
import json
import math
import re
import sqlite3
import uuid
from contextlib import contextmanager
from datetime import date, datetime, timezone
from pathlib import Path


class ResultStoreError(RuntimeError):
    """The result database or a stored payload cannot be read safely."""


def _timestamp(value, name, *, optional=False):
    if value is None and optional:
        return
    if not isinstance(value, str):
        raise ValueError(f"{name} must be an offset-aware timestamp")
    try:
        parsed = datetime.fromisoformat(value)
    except ValueError as exc:
        raise ValueError(f"{name} must be an offset-aware timestamp") from exc
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ValueError(f"{name} must be an offset-aware timestamp")


def _json(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _validate_payload(payload):
    if not isinstance(payload, dict):
        raise ValueError("payload must be an object")
    if "snapshot_id" in payload:
        raise ValueError("snapshot_id is generated by the store")
    for field in ("rows", "data_as_of", "generated_at", "trade_date", "versions",
                  "valid_until", "allow_new_buy", "selection"):
        if field not in payload:
            raise ValueError(f"missing {field}")
    _timestamp(payload["data_as_of"], "data_as_of")
    _timestamp(payload["generated_at"], "generated_at")
    _timestamp(payload["valid_until"], "valid_until", optional=True)
    try:
        date.fromisoformat(payload["trade_date"])
    except (ValueError, TypeError) as exc:
        raise ValueError("trade_date must be an ISO date") from exc
    versions = payload["versions"]
    if not isinstance(versions, dict) or any(not isinstance(versions.get(k), str) or not versions[k]
                                            for k in ("data", "strategy", "parameters")):
        raise ValueError("versions must contain data, strategy and parameters")
    if payload["allow_new_buy"] is not None and not isinstance(payload["allow_new_buy"], bool):
        raise ValueError("allow_new_buy must be boolean or null")
    if not isinstance(payload["selection"], dict) or not isinstance(payload["selection"].get("funnel"), list):
        raise ValueError("selection.funnel must be a list")
    if not isinstance(payload["rows"], list) or not isinstance(payload.get("orders", []), list):
        raise ValueError("rows and orders must be lists")
    for order in payload.get("orders", []):
        if not isinstance(order, dict):
            raise ValueError("order must be an object")
        required = ("code", "name", "action", "shares", "price_ref", "limit_low",
                    "limit_high", "amount", "weight", "stop_loss", "take_profit",
                    "reason", "warning")
        if any(key not in order for key in required):
            raise ValueError("order is missing required fields")
        if not isinstance(order["code"], str) or re.fullmatch(r"[0-9]{6}", order["code"]) is None:
            raise ValueError("order code must be a six-digit string")
        if any(not isinstance(order[key], str) or (key == "action" and not order[key].strip())
               for key in ("name", "action", "reason", "warning")):
            raise ValueError("order text fields are invalid")
        shares = order["shares"]
        if isinstance(shares, bool) or not isinstance(shares, int) or shares <= 0:
            raise ValueError("order shares must be positive")
        for key in ("price_ref", "limit_low", "limit_high", "amount", "weight",
                    "stop_loss", "take_profit"):
            value = order[key]
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"order {key} must be finite")
        if any(order[key] <= 0 for key in ("price_ref", "limit_low", "limit_high", "amount",
                                             "stop_loss", "take_profit")):
            raise ValueError("order prices and amount must be positive")
        if order["weight"] < 0 or order["limit_low"] > order["limit_high"]:
            raise ValueError("order weight or limit range is invalid")
    seen = set()
    ranks = set()
    for row in payload["rows"]:
        if not isinstance(row, dict):
            raise ValueError("row must be an object")
        code = row.get("code")
        if not isinstance(code, str) or re.fullmatch(r"[0-9]{6}", code) is None or code in seen:
            raise ValueError("row codes must be unique six-digit strings")
        seen.add(code)
        if not isinstance(row.get("name"), str):
            raise ValueError("row name is required")
        for key in ("price", "score_blend"):
            value = row.get(key)
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                raise ValueError(f"row {key} must be finite")
        if row["price"] <= 0 or not 0 <= row["score_blend"] <= 100:
            raise ValueError("row price or score out of range")
        price = row["price"]
        bracket = "low" if price <= 20 else "mid" if price <= 50 else "high" if price <= 100 else "top"
        if row.get("price_bracket") != bracket:
            raise ValueError("price_bracket does not match price")
        rank = row.get("rank")
        if isinstance(rank, bool) or not isinstance(rank, int) or rank < 1 or rank in ranks:
            raise ValueError("ranks must be positive and unique")
        ranks.add(rank)
    if ranks != set(range(1, len(payload["rows"]) + 1)):
        raise ValueError("ranks must cover the snapshot rows")
    previous_output = None
    for stage in payload["selection"]["funnel"]:
        if not isinstance(stage, dict) or not isinstance(stage.get("name"), str):
            raise ValueError("invalid funnel stage")
        for key in ("input", "output"):
            if isinstance(stage.get(key), bool) or not isinstance(stage.get(key), int) or stage[key] < 0:
                raise ValueError("invalid funnel count")
        if stage["output"] > stage["input"] or not isinstance(stage.get("excluded_by_reason"), dict):
            raise ValueError("invalid funnel stage")
        if any(isinstance(v, bool) or not isinstance(v, int) or v < 0
               for v in stage["excluded_by_reason"].values()):
            raise ValueError("invalid funnel exclusions")
        if sum(stage["excluded_by_reason"].values()) != stage["input"] - stage["output"]:
            raise ValueError("funnel exclusions do not explain the count")
        if previous_output is not None and stage["input"] != previous_output:
            raise ValueError("funnel stages are disconnected")
        previous_output = stage["output"]
    if previous_output is not None and previous_output != len(payload["rows"]):
        raise ValueError("funnel final count differs from rows")
    try:
        _json(payload)
    except (TypeError, ValueError) as exc:
        raise ValueError("payload is not finite canonical JSON") from exc


SCHEMA = """
CREATE TABLE IF NOT EXISTS result_snapshots (
    snapshot_id TEXT PRIMARY KEY,
    canonical_payload TEXT NOT NULL,
    payload_sha256 TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('staged','published','revoked')),
    job_id TEXT
);
CREATE TABLE IF NOT EXISTS result_head (
    id INTEGER PRIMARY KEY CHECK(id=1),
    snapshot_id TEXT NOT NULL REFERENCES result_snapshots(snapshot_id)
);
CREATE TABLE IF NOT EXISTS result_revocations (
    snapshot_id TEXT PRIMARY KEY REFERENCES result_snapshots(snapshot_id),
    payload_sha256 TEXT NOT NULL,
    reason_json TEXT NOT NULL,
    revoked_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS result_audit (
    id INTEGER PRIMARY KEY CHECK(id=1), projection_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS result_jobs (
    job_id TEXT PRIMARY KEY, projection_json TEXT NOT NULL, updated_seq INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS runtime_state (
    id INTEGER PRIMARY KEY CHECK(id=1), response_revision INTEGER NOT NULL
);
INSERT OR IGNORE INTO runtime_state (id,response_revision) VALUES (1,0);
"""


class ResultStore:
    def __init__(self, artifact_dir):
        self.path = (Path(artifact_dir) / "results.db").resolve()

    @contextmanager
    def _write(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        try:
            with sqlite3.connect(self.path, timeout=0.1) as db:
                db.execute("PRAGMA foreign_keys=ON")
                db.execute("PRAGMA journal_mode=WAL")
                db.execute("PRAGMA synchronous=FULL")
                db.execute("PRAGMA busy_timeout=100")
                db.executescript(SCHEMA)
                db.execute("BEGIN IMMEDIATE")
                yield db
        except sqlite3.Error as exc:
            raise ResultStoreError("result database write failed") from exc

    @staticmethod
    def _revision(db):
        db.execute("UPDATE runtime_state SET response_revision=response_revision+1 WHERE id=1")
        return db.execute("SELECT response_revision FROM runtime_state WHERE id=1").fetchone()[0]

    def stage(self, payload: dict, job_id: str | None = None) -> str:
        _validate_payload(payload)
        frozen = dict(payload)
        frozen.setdefault("orders", [])
        canonical = _json(frozen)
        digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
        snapshot_id = uuid.uuid4().hex
        with self._write() as db:
            db.execute("INSERT INTO result_snapshots VALUES (?,?,?,?,?)",
                       (snapshot_id, canonical, digest, "staged", job_id))
        return snapshot_id

    def publish(self, snapshot_id: str, expected_versions: dict | None = None,
                job_id: str | None = None) -> int:
        with self._write() as db:
            row = db.execute("SELECT canonical_payload,payload_sha256,status,job_id FROM result_snapshots WHERE snapshot_id=?",
                             (snapshot_id,)).fetchone()
            if row is None or row[2] != "staged":
                raise ValueError("snapshot is missing or not staged")
            if hashlib.sha256(row[0].encode("utf-8")).hexdigest() != row[1]:
                raise ResultStoreError("staged result payload checksum mismatch")
            payload = json.loads(row[0])
            if expected_versions is not None and payload["versions"] != expected_versions:
                raise ValueError("snapshot input versions changed")
            revoked_payloads = db.execute(
                "SELECT s.canonical_payload,s.payload_sha256 FROM result_revocations r "
                "JOIN result_snapshots s ON s.snapshot_id=r.snapshot_id"
            ).fetchall()
            for revoked_json, revoked_digest in revoked_payloads:
                if hashlib.sha256(revoked_json.encode("utf-8")).hexdigest() != revoked_digest:
                    raise ResultStoreError("revoked result payload checksum mismatch")
                revoked_versions = json.loads(revoked_json)["versions"]
                # A source revocation covers every result generated from the same frozen data.
                # Corrected inputs must carry a new data version before they can publish.
                if revoked_versions["data"] == payload["versions"]["data"]:
                    raise ValueError("revoked data version cannot be republished")
            if job_id is not None:
                if row[3] is not None and row[3] != job_id:
                    raise ValueError("snapshot belongs to another job")
                job_row = db.execute("SELECT projection_json FROM result_jobs WHERE job_id=?", (job_id,)).fetchone()
                if job_row is None:
                    raise ValueError("unknown job")
                job = json.loads(job_row[0])
                job.update(status="succeeded", stage="complete", finished_at=datetime.now(timezone.utc).isoformat(), error=None)
                db.execute("UPDATE result_jobs SET projection_json=? WHERE job_id=?", (_json(job), job_id))
            db.execute("UPDATE result_snapshots SET status='published' WHERE snapshot_id=?", (snapshot_id,))
            db.execute("INSERT INTO result_head (id,snapshot_id) VALUES (1,?) ON CONFLICT(id) DO UPDATE SET snapshot_id=excluded.snapshot_id",
                       (snapshot_id,))
            return self._revision(db)

    def revoke(self, snapshot_id: str, reason: dict) -> int:
        if not isinstance(reason, dict) or not all(isinstance(reason.get(k), str) and reason[k]
                                                    for k in ("code", "message")):
            raise ValueError("revocation requires code and message")
        with self._write() as db:
            row = db.execute("SELECT payload_sha256 FROM result_snapshots WHERE snapshot_id=?", (snapshot_id,)).fetchone()
            if row is None:
                raise ValueError("unknown snapshot")
            old = db.execute("SELECT 1 FROM result_revocations WHERE snapshot_id=?", (snapshot_id,)).fetchone()
            if old:
                return db.execute("SELECT response_revision FROM runtime_state WHERE id=1").fetchone()[0]
            db.execute("INSERT INTO result_revocations VALUES (?,?,?,?)",
                       (snapshot_id, row[0], _json({"code": reason["code"], "message": reason["message"]}),
                        datetime.now(timezone.utc).isoformat()))
            db.execute("UPDATE result_snapshots SET status='revoked' WHERE snapshot_id=?", (snapshot_id,))
            return self._revision(db)

    def record_audit(self, audit: dict) -> int:
        if not isinstance(audit, dict) or audit.get("state") not in {"passed", "pending", "running", "failed"}:
            raise ValueError("invalid audit state")
        if any(key not in audit for key in ("data_version", "parameters_version", "checked_at",
                                            "valid_until", "error", "ready")):
            raise ValueError("audit projection is incomplete")
        if audit["data_version"] is not None and not isinstance(audit["data_version"], str):
            raise ValueError("invalid audit data_version")
        if audit["parameters_version"] is not None and not isinstance(audit["parameters_version"], str):
            raise ValueError("invalid audit parameters_version")
        if not isinstance(audit["ready"], bool):
            raise ValueError("invalid audit ready flag")
        error = audit["error"]
        if error is not None and (not isinstance(error, dict)
                                  or not all(isinstance(error.get(k), str) and error[k]
                                             for k in ("code", "message"))
                                  or not isinstance(error.get("retryable"), bool)):
            raise ValueError("invalid audit error")
        for key in ("checked_at", "valid_until"):
            _timestamp(audit.get(key), key, optional=True)
        canonical = _json(audit)
        with self._write() as db:
            db.execute("INSERT INTO result_audit VALUES (1,?) ON CONFLICT(id) DO UPDATE SET projection_json=excluded.projection_json",
                       (canonical,))
            return self._revision(db)

    def save_job(self, job: dict) -> int:
        if not isinstance(job, dict) or not isinstance(job.get("job_id"), str) or not job["job_id"]:
            raise ValueError("job_id is required")
        canonical = _json(job)
        with self._write() as db:
            revision = self._revision(db)
            db.execute("INSERT INTO result_jobs VALUES (?,?,?) ON CONFLICT(job_id) DO UPDATE SET projection_json=excluded.projection_json,updated_seq=excluded.updated_seq",
                       (job["job_id"], canonical, revision))
            return revision

    def read_view(self) -> dict:
        if not self.path.exists():
            return {"snapshot": None, "revocation": None, "audit": None,
                    "job": None, "response_revision": 0}
        try:
            with sqlite3.connect(f"{self.path.as_uri()}?mode=ro", uri=True, timeout=0.1) as db:
                db.execute("PRAGMA busy_timeout=100")
                db.execute("BEGIN")
                revision = db.execute("SELECT response_revision FROM runtime_state WHERE id=1").fetchone()[0]
                head = db.execute("SELECT h.snapshot_id,s.canonical_payload,s.payload_sha256,s.status FROM result_head h LEFT JOIN result_snapshots s ON s.snapshot_id=h.snapshot_id WHERE h.id=1").fetchone()
                snapshot = None
                revocation = None
                if head:
                    if head[1] is None:
                        raise ResultStoreError("result head target is missing")
                    if head[3] not in {"published", "revoked"}:
                        raise ResultStoreError("result head points to an unpublished snapshot")
                    if hashlib.sha256(head[1].encode("utf-8")).hexdigest() != head[2]:
                        raise ResultStoreError("result payload checksum mismatch")
                    snapshot = json.loads(head[1])
                    snapshot["snapshot_id"] = head[0]
                    revoked = db.execute("SELECT reason_json FROM result_revocations WHERE snapshot_id=?", (head[0],)).fetchone()
                    revocation = json.loads(revoked[0]) if revoked else None
                    if (head[3] == "revoked") != (revocation is not None):
                        raise ResultStoreError("result revocation ledger disagrees with snapshot status")
                audit = db.execute("SELECT projection_json FROM result_audit WHERE id=1").fetchone()
                job = db.execute("SELECT projection_json FROM result_jobs ORDER BY updated_seq DESC LIMIT 1").fetchone()
                result = {"snapshot": snapshot, "revocation": revocation,
                          "audit": json.loads(audit[0]) if audit else None,
                          "job": json.loads(job[0]) if job else None,
                          "response_revision": revision}
                db.commit()
                return result
        except (sqlite3.Error, ValueError, TypeError, KeyError, IndexError) as exc:
            raise ResultStoreError("result database read failed") from exc

    def latest_job(self) -> dict | None:
        return self.read_view()["job"]

    def get_job(self, job_id: str) -> dict:
        if not self.path.exists():
            raise KeyError(job_id)
        try:
            with sqlite3.connect(f"{self.path.as_uri()}?mode=ro", uri=True, timeout=0.1) as db:
                row = db.execute("SELECT projection_json FROM result_jobs WHERE job_id=?", (job_id,)).fetchone()
                if row is None:
                    raise KeyError(job_id)
                return json.loads(row[0])
        except sqlite3.Error as exc:
            raise ResultStoreError("result job read failed") from exc
